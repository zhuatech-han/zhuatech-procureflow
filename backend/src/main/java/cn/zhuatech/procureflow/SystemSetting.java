@Entity
@Table(name = "system_setting")
public class SystemSetting {
  @Id
  @GeneratedValue(strategy = GenerationType.IDENTITY)
  public Long id;

  @Column(name = "code", nullable = false, length = 60)
  public String code;

  @Column(name = "parameter_value", nullable = false, length = 200)
  public String value;
}
